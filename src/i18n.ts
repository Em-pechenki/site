export type TKey = keyof typeof D;

function detect(): Lang {
  try {
    const q = new URLSearchParams(window.location.search).get('lang');
    if (q === 'en' || q === 'ru') return q;
    const s = localStorage.getItem(LS_KEY);
    if (s === 'en' || s === 'ru') return s;
    if ((navigator.language || '').toLowerCase().startsWith('en')) return 'en';
  } catch { /* noop */ }
  return 'ru';
}

let current: Lang = typeof window !== 'undefined' ? detect() : 'ru';
const listeners = new Set<() => void>();

function apply() {
  try {
    document.documentElement.lang = current;
  } catch { /* noop */ }
}
if (typeof window !== 'undefined') apply();

export function getLang(): Lang {
  return current;
}

export function setLang(l: Lang) {
  if (current === l) return;
  current = l;
  try {
    localStorage.setItem(LS_KEY, l);
  } catch { /* noop */ }
  apply();
  listeners.forEach((cb) => cb());
}

export function onLang(cb: () => void): () => void {
  listeners.add(cb);
  return () => {
    listeners.delete(cb);
  };
}

export function tr(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  const e = (D as Dict)[key];
  let s: string = e ? e[lang] : key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  }
  return s;
}

export function useT(): (key: string, vars?: Record<string, string | number>) => string {
  const lang = useSyncExternalStore(
    (cb) => onLang(cb),
    () => current,
    () => current,
  );
  return (key: string, vars?: Record<string, string | number>) => tr(lang, key, vars);
}

export function useLang(): Lang {
  return useSyncExternalStore(
    (cb) => onLang(cb),
    () => current,
    () => current,
  );
}
